// TestDeepCopyGenerated verifies that deepcopy-gen has been run for every type
// registered in the kube-apiserver Scheme. Each registered type must provide
// both DeepCopyInto and DeepCopy methods.
//
// TODO: This might not be needed given that runtime.Object requires DeepCopyObject be implemented.
func TestDeepCopyGenerated(t *testing.T) {
	TestAllSchemeTypes(t, func(t *testing.T, st SchemeType) {
		TestSchemeType(t, st, "must have DeepCopyInto method (deepcopy-gen)",
			hasMethod(st.Type, "DeepCopyInto"), sets.New[string]())
		TestSchemeType(t, st, "must have DeepCopy method (deepcopy-gen)",
			hasMethod(st.Type, "DeepCopy"), sets.New[string]())
	})
}

// protobufGenerated is the method set emitted by the protoc-gen-gogo variant
// used by Kubernetes.
type protobufGenerated interface {
	Reset()
	String() string
	Marshal() ([]byte, error)
	Unmarshal([]byte) error
	Size() int
}

// TestProtobufGenerated verifies protobuf generation for
// every external type registered in the Scheme.
func TestProtobufGenerated(t *testing.T) {
	TestAllSchemeTypes(t, func(t *testing.T, st SchemeType) {
		if st.IsInternal() {
			t.Skip("internal types are not serialized over the wire; no protobuf expected")
		}
		_, ok := st.Instance.(protobufGenerated)
		TestSchemeType(t, st, "must implement the protobuf method set (protobuf-gen)", ok, sets.New[string]())
	})
}

// lifecycleIntroduced is the interface produced by prerelease-lifecycle-gen.
// TODO: Export the interface so we can leverage it here?
type lifecycleIntroduced interface {
	APILifecycleIntroduced() (major, minor int)
}

// TestPrereleaseLifecycleGenerated verifies that prerelease-lifecycle generation
// for every external type registered in the Scheme.
func TestPrereleaseLifecycleGenerated(t *testing.T) {
	// DO NOT ADD NEW ENTRIES HERE.
	exempt := sets.New(
		// metav1 types registered into every GroupVersion can be ignored.
		"APIGroup.v1",
		"Status.v1",

		// Alpha API versions that pre-date prerelease-lifecycle-gen.
		"ClusterRole.v1alpha1.rbac.authorization.k8s.io",
		"ClusterRoleBinding.v1alpha1.rbac.authorization.k8s.io",
		"ImageReview.v1alpha1.imagepolicy.k8s.io",
		"PodGroup.v1alpha2.scheduling.k8s.io",
		"Role.v1alpha1.rbac.authorization.k8s.io",
		"RoleBinding.v1alpha1.rbac.authorization.k8s.io",
		"RuntimeClass.v1alpha1.node.k8s.io",
		"StorageVersion.v1alpha1.internal.apiserver.k8s.io",
		"Workload.v1alpha2.scheduling.k8s.io",
	)

	TestAllSchemeTypes(t, func(t *testing.T, st SchemeType) {
		if st.IsInternal() {
			t.Skip("internal types do not carry lifecycle markers")
		}
		obj, ok := st.Instance.(lifecycleIntroduced)
		if !ok {
			TestSchemeType(t, st, "must implement APILifecycleIntroduced (prerelease-lifecycle-gen)", false, exempt)
			return
		}
		major, minor := obj.APILifecycleIntroduced()
		TestSchemeType(t, st, "APILifecycleIntroduced must return a non-zero version",
			major != 0 || minor != 0, exempt)
	})
}

